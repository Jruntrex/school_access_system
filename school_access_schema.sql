    CONSTRAINT chk_rfid_readers_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_rfid_readers_location_id
    ON rfid_readers (location_id);

CREATE INDEX idx_rfid_readers_purpose
    ON rfid_readers (purpose);

-- =========================
-- 11. Access events
-- =========================

CREATE TABLE access_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time TIMESTAMP NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    event_source VARCHAR(30) NOT NULL,
    event_status VARCHAR(30) NOT NULL,

    reader_id BIGINT NULL,
    scanned_card_uid_hash VARCHAR(128) NULL,

    card_id BIGINT NULL,
    card_assignment_id BIGINT NULL,
    student_id BIGINT NULL,

    notes VARCHAR(255) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_access_events_reader
        FOREIGN KEY (reader_id)
        REFERENCES rfid_readers (id),

    CONSTRAINT fk_access_events_card
        FOREIGN KEY (card_id)
        REFERENCES rfid_cards (id),

    CONSTRAINT fk_access_events_card_assignment
        FOREIGN KEY (card_assignment_id)
        REFERENCES rfid_card_assignments (id),

    CONSTRAINT fk_access_events_student
        FOREIGN KEY (student_id)
        REFERENCES students (id),

    CONSTRAINT chk_access_events_event_type
        CHECK (event_type IN ('ENTER_SCHOOL', 'EXIT_SCHOOL', 'MEAL_TAKEN')),

    CONSTRAINT chk_access_events_event_source
        CHECK (event_source IN ('RFID_READER', 'MANUAL_BY_GUARD')),

    CONSTRAINT chk_access_events_event_status
        CHECK (event_status IN ('VALID', 'UNKNOWN_CARD', 'INACTIVE_CARD', 'NO_ACTIVE_ASSIGNMENT')),

    CONSTRAINT chk_access_events_rfid_fields
        CHECK (
            event_source <> 'RFID_READER'
            OR reader_id IS NOT NULL
        ),

    CONSTRAINT chk_access_events_manual_fields
        CHECK (
            event_source <> 'MANUAL_BY_GUARD'
            OR student_id IS NOT NULL
        )
);

CREATE INDEX idx_access_events_event_time
    ON access_events (event_time);

CREATE INDEX idx_access_events_student_time
    ON access_events (student_id, event_time);

CREATE INDEX idx_access_events_reader_time
    ON access_events (reader_id, event_time);

CREATE INDEX idx_access_events_card_time
    ON access_events (card_id, event_time);

CREATE INDEX idx_access_events_status
    ON access_events (event_status);

CREATE INDEX idx_access_events_scanned_card_uid_hash
    ON access_events (scanned_card_uid_hash);

