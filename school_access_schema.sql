-- =========================
-- 7. RFID cards
-- =========================

CREATE TABLE rfid_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_uid_hash VARCHAR(128) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMP NULL,
    deactivation_reason VARCHAR(30) NULL,

    CONSTRAINT uq_rfid_cards_card_uid_hash
        UNIQUE (card_uid_hash),

    CONSTRAINT chk_rfid_cards_status
        CHECK (status IN ('ACTIVE', 'LOST', 'DAMAGED', 'RETIRED')),

    CONSTRAINT chk_rfid_cards_deactivation_reason
        CHECK (
            deactivation_reason IS NULL
            OR deactivation_reason IN ('LOST', 'DAMAGED', 'REPLACED', 'STUDENT_LEFT', 'OTHER')
        )
);

CREATE INDEX idx_rfid_cards_status
    ON rfid_cards (status);

-- =========================
-- 8. RFID card assignments
-- =========================

CREATE TABLE rfid_card_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    assigned_from DATE NOT NULL,
    assigned_to DATE NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    end_reason VARCHAR(30) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_rfid_card_assignments_card
        FOREIGN KEY (card_id)
        REFERENCES rfid_cards (id),

    CONSTRAINT fk_rfid_card_assignments_student
        FOREIGN KEY (student_id)
        REFERENCES students (id),

    CONSTRAINT chk_rfid_card_assignments_dates
        CHECK (assigned_to IS NULL OR assigned_from <= assigned_to),

    CONSTRAINT chk_rfid_card_assignments_status
        CHECK (status IN ('ACTIVE', 'ENDED')),

    CONSTRAINT chk_rfid_card_assignments_end_reason
        CHECK (
            end_reason IS NULL
            OR end_reason IN ('LOST', 'DAMAGED', 'REPLACED', 'STUDENT_LEFT', 'OTHER')
        )
);

CREATE INDEX idx_rfid_card_assignments_card_id
    ON rfid_card_assignments (card_id);

CREATE INDEX idx_rfid_card_assignments_student_id
    ON rfid_card_assignments (student_id);

CREATE UNIQUE INDEX uq_active_assignment_per_card
    ON rfid_card_assignments (card_id)
    WHERE status = 'ACTIVE';

CREATE UNIQUE INDEX uq_active_assignment_per_student
    ON rfid_card_assignments (student_id)
    WHERE status = 'ACTIVE';

