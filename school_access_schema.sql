CREATE TABLE attendance_daily (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_date DATE NOT NULL,
    student_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    first_entry_time TIMESTAMP NOT NULL,
    first_entry_event_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_attendance_daily_student
        FOREIGN KEY (student_id)
        REFERENCES students (id),

    CONSTRAINT fk_attendance_daily_class
        FOREIGN KEY (class_id)
        REFERENCES classes (id),

    CONSTRAINT fk_attendance_daily_first_entry_event
        FOREIGN KEY (first_entry_event_id)
        REFERENCES access_events (id),

    CONSTRAINT uq_attendance_daily_date_student
        UNIQUE (attendance_date, student_id)
);

CREATE INDEX idx_attendance_daily_date
    ON attendance_daily (attendance_date);

CREATE INDEX idx_attendance_daily_class_date
    ON attendance_daily (class_id, attendance_date);

CREATE INDEX idx_attendance_daily_student_date
    ON attendance_daily (student_id, attendance_date);