CREATE SCHEMA IF NOT EXISTS school_access;

SET search_path TO school_access;

-- =========================
-- 1. Academic years
-- =========================

CREATE TABLE academic_years (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_academic_years_name UNIQUE (name),
    CONSTRAINT chk_academic_years_dates CHECK (starts_on < ends_on)
);

-- =========================
-- 2. Classes
-- =========================

CREATE TABLE classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id BIGINT NOT NULL,
    grade SMALLINT NOT NULL,
    letter VARCHAR(5) NOT NULL,
    name VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_classes_academic_year
        FOREIGN KEY (academic_year_id)
        REFERENCES academic_years (id),

    CONSTRAINT uq_classes_year_grade_letter
        UNIQUE (academic_year_id, grade, letter),

    CONSTRAINT chk_classes_grade
        CHECK (grade BETWEEN 1 AND 12),

    CONSTRAINT chk_classes_status
        CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX idx_classes_academic_year_id
    ON classes (academic_year_id);

-- =========================
-- 3. Students
-- =========================

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name VARCHAR(100) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_students_status
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'LEFT_SCHOOL'))
);

CREATE INDEX idx_students_name
    ON students (last_name, first_name);

-- =========================
-- 4. Student class enrollments
-- =========================

CREATE TABLE student_class_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_student_class_enrollments_student
        FOREIGN KEY (student_id)
        REFERENCES students (id),

    CONSTRAINT fk_student_class_enrollments_class
        FOREIGN KEY (class_id)
        REFERENCES classes (id),

    CONSTRAINT chk_student_class_enrollments_dates
        CHECK (valid_to IS NULL OR valid_from <= valid_to),

    CONSTRAINT chk_student_class_enrollments_status
        CHECK (status IN ('ACTIVE', 'ENDED'))
);

CREATE INDEX idx_student_class_enrollments_student_id
    ON student_class_enrollments (student_id);

CREATE INDEX idx_student_class_enrollments_class_id
    ON student_class_enrollments (class_id);

CREATE UNIQUE INDEX uq_student_active_class_enrollment
    ON student_class_enrollments (student_id)
    WHERE status = 'ACTIVE';

